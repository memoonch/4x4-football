import assert from 'node:assert/strict';
import {tournamentView} from '../webgl/ui/tournament-data.js';
const first=Array.from({length:16},(_,team)=>({team,score:-1}));
let view=tournamentView({kind:'cup',round:0,rounds:[first,[],[],[]],player:0});
assert.deepEqual(view.matches.map(column=>column.length),[8,4,2,1]);
assert.deepEqual(view.next.map(entry=>entry.name),['Argentina','Brazil']);
assert.equal(view.matches[0][0].upcoming,true);
assert.equal(view.matches[0][0].complete,false);
assert.equal(view.rounds[1][0],null);
const scored=first.map((entry,i)=>({...entry,score:i%2===0?2:0}));
const quarters=scored.filter((_,i)=>i%2===0).map(entry=>({...entry,score:-1}));
view=tournamentView({kind:'cup',round:1,rounds:[scored,quarters,[],[]],player:0});
assert.equal(view.matches[0][0].complete,true);
assert.equal(view.matches[0][0].pair[1].score,0);
assert.equal(view.matches[0][0].upcoming,false);
assert.equal(view.matches[1][0].upcoming,true);
assert.deepEqual(view.next.map(entry=>entry.team),[0,2]);
const final=tournamentView({kind:'match',round:3,rounds:[scored,quarters,[],[{team:0,score:-1},{team:15,score:-1}]],player:0});
assert.deepEqual(final.next.map(entry=>entry.name),['Argentina','USA']);
assert.throws(()=>tournamentView({kind:'match',round:4}),/Invalid/);
console.log('Tournament data: initial draw, completed scores, advancement, TBD slots, and final matchup passed.');
